# 新知识：数字与算术运算
# 数字参与计算时不加引号，例如 amount = 8。
# + 表示加法，- 表示减法，* 表示乘法（不是数学里的 ×）。
# 先乘后加减，需要改变顺序时可以使用括号。
# 例如：result = 2 * 4 + 1，result 的值是 9。
# 算出的数字也可以用 f 字符串插入输出。
#
# 情境：
# 每本笔记本 12 元，购买 3 本，另外支付一次运费 5 元。
# 你付了 50 元，请计算应付总价和找零。
#
# 任务：
# 1. 创建四个变量，分别保存以下数字（不要加引号）：
#    price：单价 12
#    quantity：数量 3
#    delivery_fee：运费 5
#    paid：付款金额 50
# 2. 使用变量和运算符计算总价，保存到 total。
#    总价包括所有笔记本的价格和一次运费。
# 3. 使用变量计算找零，保存到 change。
# 4. 输出 total 和 change 的值，可以继续使用 f 字符串。
#
# 建议输出：
# Total: 41 yuan
# Change: 9 yuan
#
# 检查重点：数字类型、乘法、加法、减法，以及用变量保存计算结果。
# total 和 change 必须由计算得到，不要直接把 41 和 9 赋给它们。
# 修改单价或数量后，计算结果也应随之变化。
# 输出说明文字可以自行调整，只要能清楚看出总价和找零即可。
# 本题不需要 input()，也不需要考虑付款不足的情况。
#
# 做完按 Ctrl+S 保存，再告诉我“检查第6题”。
#
# 请在下面写你的代码：

price = 12
quantity = 3
delivery_fee = 5
paid = 50
total = price * quantity + delivery_fee
print(f"Total: {total} yuan\nChange: {paid - total} yuan")