# 题目：
# 有 n 件物品，每 k 件组成一个完整的小组。
# 计算能组成多少个完整小组，以及还剩多少件物品。
#
# 输入格式：
# 第一行一个整数 n，表示物品总数。
# 第二行一个整数 k，表示每组的物品数。
# 范围：0 <= n <= 1_000_000_000，1 <= k <= 1_000_000。
# 每次程序运行只处理这一组数据，不需要循环读取。
#
# 输出格式：
# 按顺序输出两个整数：完整小组数、剩余物品数。建议每个数单独一行。
# 不要输出 Group:、Remaining:、输入提示或调试文字。
# 评测忽略空格、换行等空白差异，但数字内容、个数和顺序必须正确。
#
# 样例输入：
# 23
# 5
#
# 样例输出：
# 4
# 3
#
# 说明：23 件物品可以组成 4 个完整的 5 件小组，还剩 3 件。
#
# 要求：使用真实的 input() 读取 n 和 k；结果由输入计算，不能写死样例。
# 不需要条件判断、循环、列表或函数。
# 作答后 Ctrl+S 保存，再运行评测，或告诉我“检查第10题”。
# 使用方法见学习目录根部的《评测使用说明.md》。
#
# 请在下面写你的代码：

n = int(input())
k = int(input())
print(f"{n // k}\n{n % k}")