# 新知识：标准输入与整数转换
# input() 每次读取一行，返回字符串；int() 将合法的整数字符串转成整数。
# 例如 age = int(input()) 可以读取一行整数年龄。
# 连续调用两次 input()，分别读取第一行和第二行。
# 不要在 input() 的括号里写提示文字，否则这些文字也会进入输出。
