# 输入（共两行，仅处理一组，勿打印输入提示）：
# 第 1 行：两个空白分隔整数 score pass_line（0 <= score <= 100，1 <= pass_line <= 100）
# 第 2 行：一个字符串 word（长度 1～30，可能带首尾空格，清理后至少 1 个非空白字符）
