# 输出与约束（不使用循环、列表或自定义函数；按 exact 严格匹配，限时 2 秒）：
# 第 1 行：使用 if / else 判断 score 是否大于等于 pass_line，输出 PASS 或 FAIL。
# 第 2 行：判断 score 是偶数还是奇数，输出 EVEN（偶数）或 ODD（奇数）。
# 第 3 行：用 .strip() 清理 word 首尾空白得 clean_word，再用 in 配合三元表达式检查 '@' 是否在
#          clean_word 中，输出 HAS_AT 或 NO_AT。
