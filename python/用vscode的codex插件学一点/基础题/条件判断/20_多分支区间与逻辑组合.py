# 新知识：
# 1. 逻辑运算符与短路求值：
#    - and（全真才真；左边为 False 时直接得出 False，不再计算右边）
#    - or（一真即真；左边为 True 时直接得出 True，不再计算右边）
#    - not（取反）；优先级为 not > and > or，复杂条件建议加括号明确顺序。
# 2. 多分支 if / elif / else：
#    - 自上而下依次判断，一旦某一条条件成立并执行，后面的 elif / else 全部跳过。
#    - 写区间判断时必须注意分支顺序和边界端点（如 < 35 与 >= 35）。
