# 1. 拆解 `{num:02d}`：
#    - `d`（类型）：十进制整数；同类还有 `f` 浮点数、`s` 字符串、`b/o/x` 二/八/十六进制、`%` 百分比。
#    - `2`（最小宽度）：至少占 2 格；若本身位数 >= 2（如 105），不会截断，按原位数输出。
#    - `0`（前导补零）：数字左侧空位补 '0' 直到够宽；遇负数时补在负号后（f"{-5:03d}" -> "-05"）。
# 2. 对齐与填充（当指定填充字符时必须紧跟对齐符号 `<` 左、`>` 右、`^` 居中）：
#    - 省略对齐时，字符串默认左对齐，数字默认右对齐；例如 `f"{5:5d}"` -> "    5"。
#    - 指定填充符号：`f"{'PY':*^8}"` -> "***PY***"；`f"{5:0>4d}"` -> "0005"。
# 3. 常用高频组合对照：
#    - `{n:02d}`   ：整数左侧补 0 至至少 2 位（5 -> "05"，14 -> "14"）
#    - `{x:.2f}`   ：浮点数保留 2 位小数（3 -> "3.00"）
#    - `{x:8.2f}`  ：浮点数总宽至少 8 格（含小数点）、保留 2 位小数（3.14 -> "    3.14"）
#    - `{x:08.2f}` ：同上，左侧空白改补 0（3.14 -> "00003.14"）
#    - `{n:,}`     ：整数加千分位逗号（1000000 -> "1,000,000"）
#    - `{p:.1%}`   ：小数按百分比显示并保留 1 位小数（0.125 -> "12.5%"）
#
