# 先学：怎样读取一行中用空格分开的多个参数
# 假设输入一行：2.5 4
# 可以这样读取：
# width_text, height_text = input().split()
# width = float(width_text)
# height = float(height_text)
#
# 逐步理解：
# 1. input() 读取整行文字。
# 2. .split() 按空白拆开，得到多段字符串。
# 3. 左边两个变量分别接收两段文字，这叫“解包”。变量数必须和分段数一致。
# 4. 拆开的内容仍是字符串，要分别用 int() 或 float() 转换后才能计算。
# 5. 读取五个参数时，可用五个变量接收，再分别转换；本题只调用一次 input()。
#
# 推荐不带参数的 .split()：它可以处理连续多个空格、行首行尾空白和制表符。
# .split(" ") 只按单个空格分割，遇到连续空格会产生空字符串，二者不同。
# 本题使用 int()、float() 完成类型转换，不使用 eval()。
#
# 题目：
# 一笔团购订单包含单价相同的商品，商家对商品金额按百分比减免，随后加收一次运费。
# 请输出商品原价合计、最终应付金额，以及付款后应找回的金额。
#
# 规则：
# - 单价为 price，数量为 quantity。
# - discount 是减免百分比：20 表示商品金额减免20%，不是只付20%。
# - 运费 shipping 不参与减免，只收一次；即使商品数量为0也照常收取给定运费。
# - paid 是付款金额。保证付款足够，不需要处理欠款。
# - 所有中间计算保留原始精度，只在最后输出时保留两位小数。
#
# 输入格式：
# 一行五个数，顺序为：price quantity discount shipping paid
# price、shipping、paid 可能带小数，quantity、discount 是整数。
# 0 <= price <= 1000；0 <= quantity <= 1000；0 <= discount <= 100。
# 0 <= shipping <= 1000；0 <= paid <= 2000000。
# 输入的小数最多两位，参数间可能有多个空格或制表符。
# 每次运行只处理这一笔订单。
#
# 输出格式：
# 按顺序输出商品原价合计、最终应付、找零三个金额，各占一行，恰好两位小数。
# 不要输出标签、单位、输入提示或额外调试内容。
# 评测忽略空白差异，但金额、顺序和小数位数必须正确。每个测试点限时2秒。
#
# 样例输入：
# 12.5 3 20 5 50
#
# 样例输出：
# 37.50
# 35.00
# 15.00
#
# 样例说明：商品原价37.50元，减免20%后是30元，加运费5元，应付35元。
#
# 综合检查：单行输入拆分、解包、混合类型转换、百分比计算、执行顺序和格式化输出。
# 可以自行命名中间变量，独立安排计算步骤；不需要条件判断、循环或函数。
# 20组测试集中在 评测/题库/12.json，包含空白输入差异和金额边界。
# 保存后按 Ctrl+Shift+B 评测，或告诉我“检查第12题”。
#
# 请在下面写你的代码：

price, quantity, discount, shipping, paid = input().split()
total = float(price) * int(quantity)
actual = float(total) * (1 - int(discount) / 100) + float(shipping)
change = float(paid) - float(actual)
print(f"{total:.2f}\n{actual:.2f}\n{change:.2f}")