# 先学：
# 1. `while` 与 `while True` 空行结束模板（考场超高频）：
#    - `while 条件:` 当条件为真时反复执行；必须有变量向终止方向推进，否则变成死循环。
#    - 读到空行停止的多行输入标准骨架：
#      while True:
#          line = input().strip()
#          if not line:
#              break
#    - `while / else`：循环条件正常变为 False 结束（未触发 `break`）时执行 `else:`。
# 2. `random` 模块常用函数（`import random`）：
#    - `random.seed(s)`：固定随机种子，使之后生成的序列完全可复现（评测必用）。
#    - `random.randint(a, b)`：返回闭区间 `[a, b]` 的随机整数；`random.randrange(m, n, step)`：返回半开区间 `[m, n)` 以 `step` 为步长的随机整数。
#    - 另有 `random.random()`（`[0.0, 1.0)` 小数）、`random.uniform(a, b)`（`[a, b]` 小数）、`random.choice(seq)`（随机取 1 项）。
