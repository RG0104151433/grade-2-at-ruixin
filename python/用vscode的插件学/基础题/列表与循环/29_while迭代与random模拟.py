# 输出与约束（不使用列表或自定义函数；按 exact 严格匹配，限时 2 秒）：
# 1. 第 1 行（两鼠对穿每日累加）：墙厚 `wall` 尺，大鼠第 1 天打 `1.0` 尺、此后每天速度翻倍（`* 2`）；小鼠第 1 天打 `1.0` 尺、此后每天速度减半（`/ 2`）。用 `while` 按整天累计双方总进度，只要总进度 `< wall` 就继续下一天；当总进度 `>= wall` 时停止，输出 `<天数> <大鼠总进度:.2f> <小鼠总进度:.2f>`。
# 2. 第 2、3 行（不定次奇偶收集，对标 2026 春期中第 1 题）：
#    - 将上面空行前读入的所有整数中，偶数按读入顺序用 `'-'` 连接输出在第 2 行（若没有偶数输出 `NONE`）；
#    - 奇数按读入顺序用 `'+'` 连接输出在第 3 行（若没有奇数输出 `NONE`）。
# 3. 第 4 行（固定种子随机激活码，对标 2026 春期中第 2 题）：
#    - 先调用 `random.seed(seed_val)`；
#    - 循环 8 次依次生成激活码的 8 个字符：每次先掷 `a = random.randint(1, 5)`——`1` 用 `str(random.randint(0, 9))`、`2/3` 用 `chr(random.randint(ord('A'), ord('Z')))`、`4/5` 用 `chr(random.randint(ord('a'), ord('z')))`；
#    - 接着再调用一次 `random.randrange(10, 100, 5)`，按 `<8位激活码> <randrange值>` 输出在第 4 行。
