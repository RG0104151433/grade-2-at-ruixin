# 1. 列表创建、读写与二维索引：
#    - `[]` vs `list(iterable=())`：
#      * `[]` 创建空列表；`list()` 无参返回 `[]`；
#      * 传入一个可迭代对象（如字符串 `"BIT"`、元组 `(1, 2)`、`range(3)`）时，会**逐个拆开其元素**组成新列表，例：`list("BIT") -> ['B', 'I', 'T']`。注意传不可迭代的整数 `list(123)` 会报 `TypeError`。
#    - 多元素读入：`ori = []` 后 `for s in input().split(): ori.append(int(s))`。
#    - 索引修改与二维列表：正索引从 `0` 开始，负索引从 `-1`（末尾）开始，越界报 `IndexError`；列表可变，可直接 `ls[i] = val` 原地改写。
#      若列表的元素本身也是列表，即构成二维列表，例：`grid = [[5, 7], ['B', 'I', 'T']]`，则 `len(grid)` 为 `2`，`grid[0][1]` 为 `7`，`grid[1][-1]` 为 `'T'`。
#    - 拆包打印：`print(*ls)` 会把列表中元素作为多个参数传入，默认用单个空格隔开打印成一行（`print(val, "|", *ls)` 亦然）。
#
# 2. 切片读取、切片赋值与 `del` 删除：
#    - 切片读取 `ls[start:stop:step]`：
#      * 参数：`start` 起始下标（默认从头）、`stop` 结束下标（**不含**，默认到尾）、`step` 步长（默认 `1`，可为负；`ls[::-1]` 表示步长为 `-1`，从右向左切出一份反转后的**新列表**）。
#      * **切片会返回一个新列表**：`copy_ls = ls[:]` 相当于按全范围切出一份独立副本，修改 `copy_ls` 不会改动原 `ls`。
#    - 切片赋值 `ls[start:stop] = iterable`（默认 `step=1`）：
#      * 把 `[start, stop)` 这一连续区间**原地替换**成右侧可迭代对象的所有元素，**新旧长度可以不同**！例：`s = [0, 1, 2, 3]`，执行 `s[1:3] = [99, 88, 77]` 后 `s` 变为 `[0, 99, 88, 77, 3]`；赋值给 `[]` 可删除整段，`s[1:1] = [9, 8]` 可在下标 `1` 处批量插入。
#      * 若切片带了 `step != 1`（如 `s[::2] = ...`），右侧新元素个数必须与被选中的位置数严格相同，否则报 `ValueError`。
#    - `del` 语句（无返回值，原地删除）：
#      * `del ls[i]` 删除单个位置；`del ls[start:stop]` 删除连续区间；`del ls[::k]` 按步长删除离散位置（如 `del s[::2]` 删除下标 `0, 2, 4, ...` 的元素）。
#
# 3. 列表常用方法详解（⚠️ 核心共性：除 `pop()`、`index()`、`count()`、`copy()` 外，其余增删改方法均**原地修改原列表**且**返回 `None`**！切忌写成 `ls = ls.append(x)` 或 `ls = ls.reverse()`，否则变量会变成 `None`）：
#    - `ls.append(x)`：
#      * 参数：`x` 为任意单个对象。
#      * 作用：把 `x` **整个当作 1 个新元素**加到 `ls` 末尾（若 `x` 是 `[3, 4]`，会嵌套进去：`[1, 2]` 变成 `[1, 2, [3, 4]]`，长度为 `3`）。返回 `None`。
#    - `ls.extend(iterable)`：
#      * 参数：`iterable` 必须是可迭代对象（列表、元组、字符串、`range` 等，传整数会报 `TypeError`）。
#      * 作用：把 `iterable` 里的元素**逐个拆开**依次追加到 `ls` 末尾（`[1, 2].extend([3, 4])` 变成 `[1, 2, 3, 4]`，长度为 `4`；若传 `"ab"` 会追加 `'a', 'b'`）。返回 `None`。
#    - `ls.insert(index, x)`：
#      * 参数：`index` 为整数位置下标；`x` 为要插入的单个元素。
#      * 作用：在下标 `index` 前插入 `x`，原 `index` 及之后的元素整体右移，新元素最终处于下标 `index`（支持负索引；`index >= len(ls)` 时相当于插到末尾，`index < -len(ls)` 时插到开头 `0`）。返回 `None`。
#    - `ls.pop(index=-1)`：
#      * 参数：`index` 可省略，默认 `-1`（即最后一个元素）。
#      * 作用：**取出并返回**下标 `index` 处的元素，同时从原列表中删掉它！空列表调用或索引越界会报 `IndexError`。
#    - `ls.remove(value)`：
#      * 参数：`value` 为要删除的元素值。
#      * 作用：从左向右查找并删除**第一个**值等于 `value` 的元素（不会动后面再次出现的同值元素）。若列表中没有 `value` 会报 `ValueError`，不确定时应先用 `if value in ls:` 判断。返回 `None`。
#    - `ls.reverse()`：无参数，将 `ls` 原地前后颠倒，返回 `None`。
#    - `ls.clear()`：无参数，原地清空 `ls` 中的全部元素（`ls` 变为 `[]`），返回 `None`。
#    - 查询辅助：`ls.count(value)` 统计 `value` 出现次数；`ls.index(value, start=0, stop=...)` 返回指定区间内第一次出现的下标（找不到报 `ValueError`）。
#
# 4. 二维列表（二维数组）的初始化与避坑：
#    - Python 没有专门的二维数组类型，二维数组本质是“列表里套列表”；`len(mat)` 是行数，`len(mat[0])` 是列数，`mat[i][j]` 先取第 `i` 行再取第 `j` 列。
#    - 三种正确的初始化方式：
#      ① 逐行 `append` 组装（适合各行长度/类型不同，或逐行读入）：
#         `mat = []` 后在 `for _ in range(n):` 中向 `mat.append([int(x) for x in input().split()])`；
#      ② 列表推导式创建固定初值 `n × m` 矩阵（最推荐）：
#         `mat = [[0] * m for _ in range(n)]` —— 外层循环每轮都会创建**独立的新行列表**，改 `mat[0][1]` 不会影响其他行（注意内层 `* m` 仅适用于数字/字符串/`None` 等不可变初值）；
#      ③ 传统双层 `for` 循环：`mat = []`，外层建 `row = []`，内层 `row.append(0)` 后再 `mat.append(row)`。
#    - ⚠️ 高频大坑：严禁写成 `mat = [[0] * m] * n`！
#      因为外层 `* n` 只是把**同一个一维子列表的引用**复制了 `n` 次（`mat[0] is mat[1]` 为 `True`），修改 `mat[0][0] = 9` 会让所有行的第 0 列同时变成 `9`。
