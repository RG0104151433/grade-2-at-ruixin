# 思考1：`append()` 和 `reverse()` 都是原地修改列表且返回 `None`；写成 `ls = ls.append(10)` 或 `ls = ls.reverse()` 会把变量重新绑定成 `None` 并丢失原列表，后续再调用列表方法就会报 `AttributeError`。`pop()` 会返回被删除的那个元素（默认弹出最后一个），而 `remove()` 只删除首个匹配元素且返回 `None`。
# 思考2：`a.append([3, 4])` 把 `[3, 4]` 整体当成 1 个子列表元素加到末尾，变为 `[1, 2, [3, 4]]`，`len(a)` 为 `3`；`a.extend([3, 4])` 把 `[3, 4]` 的元素逐个拆开追加，变为 `[1, 2, 3, 4]`，`len(a)` 为 `4`。