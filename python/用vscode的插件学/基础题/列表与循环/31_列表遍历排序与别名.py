# 1. 列表推导式与统计内置函数：
#    - 列表推导式语法：
#      * `[expr for x in iterable]`：对每个元素做变换后生成新列表，如 `[int(s) for s in input().split()]`；
#      * `[expr for x in iterable if cond]`：只保留满足 `cond` 的元素，如 `[x for x in nums if x >= 0]`；
#      * 比“先建空表再反复 `append`”更简洁，且会生成一个**全新列表**。
#    - 聚合统计内置函数：
#      * `sum(iterable, start=0)`：对数值序列累加求和，可选第 2 参数 `start` 为累加初值（默认 `0`）；空列表返回 `start`（即 `0`）。
#      * `min(iterable, *, key=None, default=...)` / `max(iterable, *, key=None, default=...)`：
#        取可迭代对象最小/最大值（也支持传多个直接参数 `min(a, b, c)`）；可选关键字参数 `key` 按指定规则比较（如 `max(words, key=len)`）；
#        ⚠️ **空列表直接 `min([])` / `max([])` 会报 `ValueError`**，处理不确定是否为空的结果时要么先 `if ls:` 判断，要么传 `default=`。
#    - 探索方法：`dir(list)` 列出列表全部方法与属性名，`help(list.sort)` 可查看具体参数签名。
#
# 2. `enumerate()` 与 `zip()` 并行遍历：
#    - `enumerate(iterable, start=0)`：
#      * 参数：`iterable` 为任意可迭代对象；`start` 为起始编号整数，默认 `0`（生成 `1, 2, 3...` 排名时常写 `start=1`）。
#      * 返回值：迭代器，每次产出 `(序号, 元素)` 二元组，通常拆包使用：`for idx, val in enumerate(ls, start=1):`。
#    - `zip(*iterables, strict=False)`：
#      * 参数：传入多个可迭代对象（如 `zip(names, scores)`），按位置把第 `k` 个元素打包成元组 `(name_k, score_k)`；
#      * 长度不等时默认在**最短**的序列耗尽时停止（Python 3.10+ 若指定关键字参数 `strict=True` 会在不等长时报 `ValueError`）。
#    - 注意：两者返回的都是**惰性迭代器**（只能遍历一轮），可直接放进 `for`、`list(...)` 或 `sorted(...)` 中使用。
#
# 3. `list.sort()` vs `sorted()`（所有参数、返回值与多关键字用法）：
#    - `ls.sort(*, key=None, reverse=False)`（列表方法）：
#      * **原地修改** `ls` 本身，**返回 `None`**（不要写 `a = ls.sort()`！）。
#    - `sorted(iterable, /, *, key=None, reverse=False)`（内置函数）：
#      * 接收任意可迭代对象（列表、元组、字符串、`zip(...)` 等），**不修改原对象**，返回**排好序的新列表**。
#    - 参数详解：
#      * `reverse`：默认为 `False`（升序）；`True` 为降序。
#      * `key`：默认 `None`（直接比元素大小）；可传一个**单参数函数**，排序时用 `key(元素)` 的返回值作比较依据（原元素位置跟着移动，但元素值本身不被改写）。
#      * **多关键字排序（元组法）**：让 `key` 返回元组 `(第一关键字, 第二关键字)`。例如：
#        - `key=lambda x: (abs(x), -x)`：先按绝对值 `abs(x)` 升序；绝对值相同时，再按 `-x` 升序（数值越大 `-x` 越小，等价于同绝对值按原值**降序**，如 `3` 排在 `-3` 前）；
#        - `key=lambda item: (-item[1], item[0])`：对 `(姓名, 分数)` 二元组先按分数降序（`-item[1]`），同分再按姓名升序（`item[0]`）。
#        - 说明：Python 排序具有**稳定性**（当 `key` 完全相等时，保留元素原有的先后顺序）。
#
# 4. 两大高发陷阱：
#    - **引用别名 `lt = ls` vs 浅拷贝 `ls.copy()` / `ls[:]` / `list(ls)`**：
#      * 写成 `lt = ls` 只是给同一块内存起别名（`lt is ls` 为 `True`），改 `lt[0]` 或调用 `lt.sort()` 会直接把 `ls` 一起改掉！
#      * 调用无参方法 `ls.copy()`、全切片 `ls[:]` 或 `list(ls)` 会创建**独立的新外层列表**（`lt is ls` 为 `False`），对一维数字/字符串列表互相独立（浅拷贝：若元素本身还是可变子列表，子列表仍共享，深层独立需 `copy.deepcopy`）。
#    - **遍历时原地 `remove()` 漏删**：
#      * 若写 `for x in a: if x == 2: a.remove(x)`，删掉当前元素后右侧元素整体左移，迭代下标却继续右移 1 格，导致紧邻的下一个元素被跳过！正确做法是用推导式 `[x for x in a if x != 2]` 重建，或遍历 `a[:]` 副本。
