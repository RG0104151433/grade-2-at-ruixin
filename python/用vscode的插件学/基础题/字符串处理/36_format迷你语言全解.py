# 先学（本节重点：系统吃透 str.format() 与 f-string 共用的迷你排版语言与全部类型符）：
#
# 1. 参数定位（冒号前面）：
#    - "{0} {1}".format(a, b) 按位置编号从 0 取参（可多次复用，如 "{0:b} {0:x}".format(n)）；
#    - "{name}".format(name=val) 按关键字取参；省略编号 {} 按先后顺序取；混合传参时关键字参数必须放在位置参数后面（否则 SyntaxError）。
#
# 2. 格式说明完整语法（冒号后面，str.format() 与 f-string 完全通用；返回值均为新字符串 str）：
#    {[参数定位]:[填充字符][对齐 < > ^ =][符号 + - 空格][#][0][最小宽度][千分位 ,][.精度][类型]}
#    - 对齐与填充：
#      * '<' 左对齐、'>' 右对齐、'^' 居中对齐（差额奇数时左少 1、右多 1）；'=' 仅用于数字，把填充字符放在正负号后面；
#      * 省略对齐时：**字符串默认左对齐，数字默认右对齐**；省略填充字符时默认空格。
#    - **带符号前导补零的正确写法**：
#      * 若希望输出如 "+0000042"（正负号在最左端，号与数字之间用 '0' 补到总宽 8 位），可直接写成 "{:+08d}".format(42)（即符号 + 写在 0 前面；0 会自动启用符号后补零，不需要写成 <0）。
#      * 警告：不要写成 "{:<08d}"，左对齐配 0 会在右边补零变成 "+4200000"！
#    - 整数进制与字符类型（⚠️ 与 bin/oct/hex/chr 的核心差异；全部返回新字符串 str）：
#      * 类型符：b（二进制）、o（八进制）、d（十进制）、x（小写十六进制）、X（大写十六进制）、c（把整数码转为 Unicode 单个字符）。
#      * 默认不带前缀："{:b}".format(42) -> "101010"、"{:x}".format(42) -> "2a"、"{:c}".format(65) -> "A"（而 bin(42) 返回 '0b101010'）。
#      * '#' 带前缀开关（Alternate Form）：写在引号花括号的冒号后面、宽度/0 前面（不是注释），用于让进制输出自动带上前缀：
#        - "{:#b}".format(42) -> "0b101010"，"{:#o}".format(42) -> "0o52"，"{:#x}".format(42) -> "0x2a"，"{:#X}".format(42) -> "0X2A"；
#        - 配合位置索引或补零宽度："{0:#b}".format(42) -> "0b101010"，"{:#06x}".format(42) -> "0x002a"（前缀 0x 也计入总宽 6 位）。
#        - f-string 同理：f"{42:#x}" -> "0x2a"。本题第 1 行要求**无前缀**，所以不要加 '#'。
#    - 千分位、科学计数与百分比：
#      * ',' 加千分位分隔符，如 "{:,.2f}".format(12345.6789) -> "12,345.68"；
#      * 'e' / 'E' 科学计数法（如 "{:.2e}".format(12345.6789) -> "1.23e+04"）；
#      * '%' 先乘 100 再加百分号（如 "{:.1%}".format(0.125) -> "12.5%"）。
#    - **最小宽度 vs .精度 的重要区别（数字 vs 字符串）**：
#      * 最小宽度不够时**永远不截断**（"{:>4}".format("Python") 仍输出 "Python"）；
#      * 对浮点数 .n 控制小数位数；对**字符串**指定 .n（如 "{:*^8.3}".format("caterpillar")）会**先把原串截断成前 n 个字符 "cat"**，再按宽度 8 居中补 * 得 "**cat***"！
#    - 动态嵌套槽：宽度、填充符、精度均可套用变量，如 "{:{ch}^{w}.{k}}".format(word, ch=fill, w=width, k=limit)（关键字或位置嵌套皆可）。
#
# 3. 补充：'\r' 回车单行刷新（课件 lec3 文本进度条）：
#    - '\r' 只把光标退回到当前行开头而不换行，配合 print("\r{:3d}%".format(i), end="") 可实现命令行原地刷新进度条。
#    - 注意：在自动化标准输出评测中不要输出多余 '\r'（它会被当作普通输出字符参与严格比对）。
#
# 输入（3 行，勿打印输入提示）：
