N, Code_pt = input().split()
n, code_pt = int(N), int(Code_pt)
Money, Ratio = input().split()
money, ratio = float(Money), float(Ratio)
word, fill, width, limit = input().split()

print(f"{n:b} | {n:o} | {n:d} | {n:x} | {n:X} | {code_pt:c}")

print(f"{money:,.2f} {money:.2e} {ratio:.1%}")

print(f"[{word:{fill}^{width}.{limit}}]")

print(f"[{n:+08d}|{word:10.{limit}}]")

# 思考1：对字符串 "{:8.3}".format("caterpillar") 而言，".3" 表示先把原字符串截断为最多前 3 个字符（"cat"），再在最小宽度 8 格内默认左对齐补空格（得 "cat     "）；而对浮点数 "{:8.3f}".format(12.3456) 而言，".3f" 表示将小数部分四舍五入保留 3 位小数（得 "  12.346"），不会截断整数位。
# 思考2："{:<+08d}".format(42) 会输出 "+4200000"！因为写了 "<" 强制左对齐，后面的 "0" 只能在右侧空白处补零；想把正负号留在最左端、中间用 0 补齐，应去掉 "<" 直接写 "{:+08d}"（或用 "=" 对齐符写 "{:+=08d}"）。