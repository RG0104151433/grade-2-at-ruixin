# 第 2 行：两个空格分隔浮点数 money ratio（money 可正可负，0.0 <= ratio <= 1.0）。
# 第 3 行：四个空格分隔字段 word fill width limit（word 非空无空格串，fill 为 1 个非空格字符，4 <= width <= 30，1 <= limit <= 15）。
