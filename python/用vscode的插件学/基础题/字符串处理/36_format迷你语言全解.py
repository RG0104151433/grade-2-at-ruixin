#    ① 左栏占总宽 8 位：n 必须显式带正负号（0 也带 '+'），右对齐且符号与数字之间用 '0' 补齐；
#    ② 右栏占总宽 10 位：截断到最多前 limit 个字符后的 word，用**字符串默认对齐方向**以空格填充至最小宽度 10。
