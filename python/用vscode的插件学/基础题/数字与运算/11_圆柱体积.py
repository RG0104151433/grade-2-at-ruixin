# 新知识：
# - float(input()) 可以读取带小数的数，例如 2.5；也可以读取整数形式的输入。
# - ** 表示乘方，例如 4 ** 2 是 16；^ 不是乘方运算符。
# - f"{value:.2f}" 将 value 按固定两位小数显示，例如 7 显示为 7.00。
#   格式化会对显示结果进行舍入，并不会改变 value 的值。
#   先完成计算，最后输出时再格式化，不要提前对中间结果舍入。
#
# 题目：
# 已知圆柱的底面半径 r 和高 h，计算它的体积。
# 体积公式：V = π × r² × h。
# 本题固定使用 π = 3.14，不要改用其他圆周率值。
#
# 输入格式：
# 第一行一个数 r，第二行一个数 h。每次运行只处理一个圆柱。
# 范围：0 <= r <= 100，0 <= h <= 1000；输入最多有两位小数。
#
# 输出格式：
# 只输出体积这一个数，必须恰好有两位小数，不输出单位或标签。
# 忽略输出首尾空白，但数字和两位小数的格式必须正确。
# 时间限制：每个测试点2秒。
#
# 样例输入：
# 2
# 5
#
# 样例输出：
# 62.80
#
# 要求：使用真实输入和乘方运算计算；不写死答案。
# 不需要条件判断、循环、列表、函数或额外导入模块。
#
# 测试资料已集中在 评测/题库/11.json，共14组。
# 保存后按 Ctrl+Shift+B 评测，或者告诉我“检查第11题”。
#
# 请在下面写你的代码：

r = eval(input())
h = eval(input())
v = 3.14 * h * (r ** 2)
print(f"{v:.2f}")