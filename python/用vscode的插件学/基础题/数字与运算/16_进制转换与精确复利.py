# 第 2 行：<进步结果:.2f> <退步结果:.2f>
# 第 3 行：<Decimal("0.1") + Decimal(x) 的精确结果>
#
# 样例输入：
# 10 0.001 0.2
#
# 样例输出：
# 0b1010 0o12 0xa
