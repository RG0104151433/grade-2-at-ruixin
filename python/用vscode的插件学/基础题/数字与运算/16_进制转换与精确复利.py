# 新知识：
# 1. 多进制表示与转换：
#    - Python 整数除了十进制，还支持 0b(二进制)、0o(八进制)、0x(十六进制) 字面量，例如 0x1a9 == 425。
#    - bin(n)、oct(n)、hex(n) 可将整数 n 分别转为带前缀的二进制、八进制、十六进制字符串。
# 2. math 模块与乘方：
#    - import math 后可用 math.pow(x, y)、math.sqrt(x)、math.pi 等。
# 3. 浮点数误差与 decimal.Decimal：
#    - 计算机用二进制存储小数，十进制的 0.1 和 0.2 在二进制中是无限循环小数，
#      因此 0.1 + 0.2 的结果不是精确的 0.3（约为 0.30000000000000004）。
#    - 需要精确十进制加减时，可用 from decimal import Decimal，
#      并务必传入字符串构造：Decimal("0.1") + Decimal("0.2")，结果精确为 0.3。
#      注意：不要写成 Decimal(0.1)，因为传入 float 会把已有的二进制误差也带进去。
#
# 题目：
# 读取一行由空白分隔的三个参数：n r x（使用 input().split() 读取并解包）。
# 请依次完成以下三项计算与输出：
# 1. n 是一个非负整数：输出它的二进制、八进制、十六进制字符串，用单个空格隔开。
# 2. r 是每日变化率小数（如 0.001）：将其转为 float 后，结合 math.pow() 分别计算
#    “一年 365 天每天进步 r”即 (1 + r)^365，和“每天退步 r”即 (1 - r)^365 的结果，
#    各保留两位小数，用单个空格隔开。
# 3. x 是一个十进制小数字符串（注意不要先转成 float）：
#    用 Decimal("0.1") + Decimal(x) 精确计算两者之和，直接输出该精确结果。
#
# 输入格式：
# 一行三个参数：n r x，参数间可能有多个空格。
# 范围：0 <= n <= 100000（整数）；0 <= r <= 0.05（最多 4 位小数）；0 <= x <= 100（最多 3 位小数）。
