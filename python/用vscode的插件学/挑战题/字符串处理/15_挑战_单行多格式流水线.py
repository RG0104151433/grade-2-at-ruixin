#
# 请在下面写你的代码：

raw = input()
seg1, seg2, seg3 = raw.split("|")
command = seg1.lstrip(" >*").rstrip(" ").center(30,'-')
route = seg2.strip("[ ]")
ch = seg3.strip().upper()
result = "{}\t{}:{}({})".format(route, ch, chr(ord(ch)+1), ord(ch))
print(f"RAW:\"{raw}\"\n{command}\n{result}")