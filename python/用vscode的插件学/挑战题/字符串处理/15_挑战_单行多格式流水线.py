# 题目：
# 系统收到一条格式杂乱的单行命令记录，由 '|' 分隔成三段，依次为：
# 1. 命令代号段：左侧可能混有多余的空格、'>'、'*'，右侧可能有多余空格；
#    注意：命令代号本身的末尾或中间可能合法带有 '*' 或 '>'（例如 "  >>*build*  " 的合法代号是 "build*"）。
#    要求：只清理左侧多余的空格、'>'、'*'，以及右侧多余的空格；保留代号内部和末尾合法的 '*'、'>' 及原有字母大小写。
# 2. 路径标签段：首尾可能混有空格、'['、']'，中间可能含空格、反斜杠 '\' 或方括号（如 "[[a[0]/b]]"）。
#    要求：剥离首尾两端的空格和 '['、']'，中间内容原样保留。
# 3. 标记字符段：首尾可能有空格，去掉空格后恰好是 1 个英文字母。
#    要求：转为大写，记作 tag；计算其 ASCII 码 code，以及下一个 ASCII 字符 next_ch（即编码为 code + 1）。
#
# 输出要求（共 3 行，严格按字符匹配 exact，限时 2 秒）：
# 第 1 行：RAW:"<原始整行输入>"   （必须完整保留输入原样，包括原始首尾空格和各段修饰符）
# 第 2 行：将处理后的命令代号在总宽 30 个字符内居中，两侧用 '-' 填充（若代号长度 >= 30 则原样输出）。
# 第 3 行：<路径标签>\t<tag>:<next_ch>(<code>)   （即路径标签、制表符 \t、大写字母:下一字符(ASCII码)，括号内无多余空格）
#
# 输入格式：
# 一行文本 raw_line，恰好包含两个 '|'，不含双引号和换行，长度不超过 120。
# 每次运行只处理这一行输入，不要打印提示文字。
#
# 样例输入：
#   >>*build*  |  [src\core]  |  a  
#
# 样例输出：
# RAW:"  >>*build*  |  [src\core]  |  a  "
# ------------build*------------
# src\core	A:B(65)
#
# 代码末尾附加说明（请用 # 注释写一句，检查时我会审阅）：
# 为什么第一段命令代号不能直接用 .strip(" >*") 处理？
#
# 约束：不使用 if、循环、列表下标或自定义函数。
# 先独立拆解步骤；遇到困难可以说“给第15题一个提示”。
# 12 组测试集中在 评测/题库/15.json。
