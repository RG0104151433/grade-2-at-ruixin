# 先学（挑战题减少解法提示，只明确罗马数字规则、字符编码与序列比较边界，均标明返回类型）：
# 1. 序列字典序比较、ASCII 判断与字符串拼接惯用法：
#    - 序列比较（str / tuple / list 通用，返回 bool）：比较 "ab" < "aba" 或 [1, 2] < [1, 3] 时，从下标 0 起逐位比较元素的大小（字符串按每个字符的 ord() 比较，如 "Z" < "a" 为 True）；若前缀完全相同，则较短的序列更小。
#    - s.isascii() -> bool（无参数）：判断字符串是否全部由 ASCII 字符（编码 0～127，含英文字母、数字、常见英文标点与空白）组成，空串也返回 True。
#      ⚠️ 注意：s.isalpha() 和 s.isalnum() 会把中文汉字等非 ASCII 字母也判定为 True；若题目严格限定“仅英文/ASCII 字母数字”，需与 isascii() 配合或显式判断编码范围。
#    - 不可变字符串的高效构造：循环内频繁 res += ch 会不断拷贝生成新串；通常把字符或片段先 append() 进列表，最后用 "".join(parts) -> str 一次拼成完整字符串。
