# 1. 凯撒移位密码原理（对标 23 级 pretest 第 12 题）：
#    - 将单词每个字符的 ord() 码（返回 int）累加再对 26 取余（sum % 26），可得循环移位量 shift。
#    - 单个英文字母循环右移 shift 位（支持正负及大于 26 的移位）：
#      * 先求相对起点：大写字母基准为 ord('A')，小写字母基准为 ord('a')；
#      * 新编码 = (ord(ch) - base + shift) % 26 + base，再用 chr(...) 转回单个字符 str；
#      * 注意对非字母字符（数字、空格、标点等）原样保留。
# 2. 字符串对齐、大小写与分割拓展方法（⚠️ 以下方法均不改原串，全部返回新字符串 str 或对应列表/元组）：
#    - 大小写拓展（无参数，返回新 str）：
#      * s.capitalize() -> str：只把整串第 1 个字符变大写、其余全变小写（区别于 .title() 每个单词首字母大写）；
#      * s.swapcase() -> str：大写变小写、小写变大写（如 "PyThOn".swapcase() -> "pYtHoN"）。
#    - 独立对齐与补零（返回新 str；除了用 format()，单串填充也可直接调方法）：
#      * s.ljust(width, fillchar=' ') / s.rjust(width, fillchar=' ') -> str：左对齐/右对齐到最小宽度 width（默认填空格，不截断超长串）；
#      * s.zfill(width) -> str：在左侧用 '0' 补齐到 width 位，若带 '+'/'-' 符号则自动把 '0' 补在符号后面（如 "-42".zfill(6) -> "-00042"）。
#    - 三段式切分与行切分：
#      * s.partition(sep) / s.rpartition(sep) -> tuple(3 个 str)：按首次/末次出现的 sep 切一次，返回三元组 (左段, sep, 右段)；找不到 sep 时分别返回 (s, '', '') 或 ('', '', s)，不会报错；
#      * s.splitlines(keepends=False) -> list[str]：按换行符（\n、\r\n 等）切分为每行组成的列表，keepends=True 时保留行尾换行符。
# 3. 序列查表、一维数据解析与格式对齐（课件 lec3 / lec6）：
