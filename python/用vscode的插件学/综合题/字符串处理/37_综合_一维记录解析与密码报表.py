#    - str.format() / f-string 对齐组合：如 "{:<10}|{:^10}|{:>4d}|{}".format(a, b, c, d) -> str（整数右对齐 d 不能传浮点数；^ 居中差额奇数时左少 1、右多 1）。
#    - 统一替换数字为 '*'：可构造含 "0123456789" -> "**********" 的映射表配合 translate(table) -> str，也可使用 string.digits。
# 4. 中文文本分词概念拓展（课件 lec6 选修认知，本题暂不调用第三方库）：
#    - Python 处理中文文本常用第三方库 jieba，提供三种核心分词模式（均返回分词后的字符串列表 list[str]）：
#      ① 精确模式 jieba.lcut(s) -> list[str]：最常用，精确切开无冗余；
#      ② 全模式 jieba.lcut(s, cut_all=True) -> list[str]：把句子中所有可能成词的组合都扫出来，速度最快但有冗余；
#      ③ 搜索引擎模式 jieba.lcut_for_search(s) -> list[str]：在精确模式基础上对长词再次切分，适合检索建索引。
